function extractPaths(svg: string): string[] {
  return [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
}

async function readSvgPaths(dir: string, file: string): Promise<string[] | null> {
  try {
    const svg = await readFile(join(dir, file), 'utf8')
    const paths = extractPaths(svg)
    return paths.length > 0 ? paths : null
  } catch {
    return null
  }
}

async function walkSourceFiles(dir: string, out: string[] = []): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    const abs = join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === 'generated') continue
      await walkSourceFiles(abs, out)
    } else if (/\.(ts|tsx)$/.test(entry.name)) {
      out.push(abs)
    }
  }
  return out
}

async function collectFromSource(): Promise<Set<string>> {
  const names = new Set<string>(STATIC_ICONS)
  const files = await walkSourceFiles(SRC)

  const patterns = [
    /icon:\s*['"]([a-z0-9-]+)['"]/g,
    /<Icon[^>]*\sname=["']([a-z0-9-]+)["']/g,
  ]

  for (const file of files) {
    const text = await readFile(file, 'utf8')
    for (const re of patterns) {
      re.lastIndex = 0
      let m: RegExpExecArray | null
      while ((m = re.exec(text))) {
        const n = m[1]
        if (n && !n.includes('$') && !n.includes('{')) names.add(n)
      }
    }
  }

  return names
}

async function main() {
  const seeds = await loadSkillSeeds()
  const names = await collectFromSource()

  for (const c of CATEGORIES) names.add(c.icon)
  for (const s of STACKS) names.add(s.icon)
  for (const s of seeds) names.add(s.icon)
  for (const c of COLLECTIONS) names.add(c.icon)

  const entries: Array<{ id: string; paths: string[] }> = []
  const missing: string[] = []

  for (const name of [...names].sort()) {
    const regular = await readSvgPaths(PHOSPHOR_REG, `${name}.svg`)
    const bold = await readSvgPaths(PHOSPHOR_BOLD, `${name}-bold.svg`)

    if (regular) entries.push({ id: `ph-${name}`, paths: regular })
    else missing.push(`${name} (regular)`)

    if (bold) entries.push({ id: `ph-bold-${name}`, paths: bold })
    else if (regular) entries.push({ id: `ph-bold-${name}`, paths: regular })
    else missing.push(`${name} (bold)`)
  }

  const fallback = await readSvgPaths(PHOSPHOR_REG, 'question.svg')
  if (fallback) {
    entries.push({ id: 'ph-fallback', paths: fallback })
    entries.push({ id: 'ph-bold-fallback', paths: fallback })
  }

  const body = entries
    .map(({ id, paths }) => {
      const pathLines = paths
        .map((d) => `    ${JSON.stringify(d)},`)
        .join('\n')
      return `  ${JSON.stringify(id)}: [\n${pathLines}\n  ],`
    })
    .join('\n')

  const file = `// Generated by scripts/generate-phosphor-sprite.ts — do not edit.
export const PHOSPHOR_SPRITE_PATHS: Record<string, readonly string[]> = {
${body}
}

export const PHOSPHOR_SPRITE_ICON_COUNT = ${names.size}
`

  await writeFile(OUT, file, 'utf8')
  console.log(`phosphor sprite: ${names.size} icons, ${entries.length} symbols → ${OUT}`)
  if (missing.length) {
    console.warn(`missing (${missing.length}):`, missing.slice(0, 12).join(', '), missing.length > 12 ? '…' : '')
  }
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
